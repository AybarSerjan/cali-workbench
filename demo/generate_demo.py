"""Create synthetic calibration demo inputs without reading any engineering files."""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path

import numpy as np
from asammdf import MDF, Signal


def dump(path: Path, value: object) -> None:
    path.write_text(json.dumps(value, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")


def generate(out: Path) -> dict:
    if out.exists() and any(out.iterdir()):
        raise ValueError("Choose an empty output directory; existing files are never overwritten.")
    out.mkdir(parents=True, exist_ok=True)
    measurements = out / "measurements"
    measurements.mkdir()
    t = np.arange(601, dtype=float) / 10
    channels = {
        "engine_rpm": ("rpm", "Synthetic engine speed"),
        "engine_load": ("%", "Synthetic load"),
        "lambda_actual": ("", "Synthetic measured lambda"),
        "lambda_target": ("", "Synthetic requested lambda"),
        "coolant_temp": ("degC", "Synthetic coolant temperature"),
        "fuel_rate": ("L/h", "Synthetic fuel rate; toy formula"),
    }
    expected = []
    for rpm in (1000, 2000, 3000):
        for load in (20, 50, 80):
            anomaly = rpm == 2000 and load == 50
            actual = 1 + 0.005 * np.sin(t / 2)
            if anomaly:
                actual[(t >= 20) & (t <= 24)] += 0.12
            values = {
                "engine_rpm": rpm + 10 * np.sin(t / 5),
                "engine_load": load + 0.2 * np.sin(t / 3),
                "lambda_actual": actual,
                "lambda_target": np.ones(len(t)),
                "coolant_temp": 80 + 1.5 * np.sin(t / 10),
                "fuel_rate": 0.2 + 0.0002 * rpm * load + 0.02 * np.sin(t),
            }
            name = f"SYNTHETIC_N{rpm // 100}_RL{load}.mf4"
            with MDF(version="4.10") as mdf:
                mdf.header.author = "SYNTHETIC_DEMO"
                mdf.header.department = "SYNTHETIC_DEMO"
                mdf.header.project = "SYNTHETIC_DEMO"
                mdf.header.subject = "Not vehicle measurements"
                mdf.header.start_time = datetime(2000, 1, 1, tzinfo=timezone.utc)
                mdf.header.comment = "Entirely generated by equations. No customer or vehicle data."
                mdf.append([Signal(values[key], t, name=key, unit=unit, comment=comment)
                            for key, (unit, comment) in channels.items()])
                mdf.save(measurements / name, overwrite=False)
            expected.append({"file": f"measurements/{name}", "expected_verdict": "FAIL" if anomaly else "PASS",
                             "expected_anomaly_window_s": [20.0, 24.0] if anomaly else None})

    lines = ['ASAP2_VERSION 1 71', '/begin PROJECT SYNTHETIC "Synthetic demo only"',
             '/begin MODULE DEMO "No ECU or vehicle association"',
             '/begin MOD_COMMON "" BYTE_ORDER MSB_LAST /end MOD_COMMON',
             '/begin COMPU_METHOD IDENTITY "" IDENTICAL "%8.3" "" /end COMPU_METHOD']
    for key, (unit, comment) in channels.items():
        lines.append(f'/begin MEASUREMENT {key} "{comment}" FLOAT32_IEEE IDENTITY 1 0 -100000 100000 /end MEASUREMENT')
    lines.extend(['/end MODULE', '/end PROJECT'])
    (out / "synthetic_measurements.a2l").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    (out / "synthetic_source.md").write_text(
        "# Synthetic lambda example\n\n"
        "This document and all accompanying values were created from toy equations. "
        "They contain no vehicle, customer, employee, ECU calibration, or supplier documentation.\n\n"
        "Six channels are sampled at 10 Hz for 60 seconds across nine operating points. "
        "Requested lambda is 1.0. Measured lambda is 1 + 0.005 * sin(t / 2). "
        "Only N20_RL50 has an artificial +0.12 offset from 20.0 through 24.0 seconds.\n\n"
        "The demonstration flags abs(lambda_actual - lambda_target) > 0.05 for at least "
        "0.5 seconds. This limit is invented for a software demo and is not a calibration "
        "recommendation, regulatory limit, or validation criterion for a real vehicle.\n",
        encoding="utf-8", newline="\n")
    dump(out / "workpackage.json", {
        "wp_code": "DEMO-LAMBDA", "title": "SYNTHETIC: detect a deliberately injected lambda offset",
        "definition": {
            "description": "Toy rule and entirely synthetic inputs; not valid for real engineering decisions.",
            "signals": [{"a2l_name": key, "match_status": "confirmed"} for key in ("lambda_actual", "lambda_target")],
            "scenario_gate": "lambda_target > 0.5",
            "criteria": [{"id": "synthetic-offset", "expression": "abs(lambda_actual - lambda_target) > 0.05",
                          "min_duration_s": 0.5, "threshold_source": "SYNTHETIC_DEMO_ONLY"}],
        }, "created_by": "user"})
    dump(out / "mf4_pipeline_config.json", {
        "data_cleaning": {"trim_start": 5.0, "trim_end": 5.0, "min_duration": 10.0, "realign": True},
        "statistics": {"default_metrics": ["mean", "max", "min", "std", "median"],
                       "signals": {key: {"description": comment, "unit": unit} for key, (unit, comment) in channels.items()},
                       "calculated_signals": {"lambda_error": {"description": "Toy lambda difference", "unit": "",
                            "formula": "lambda_actual - lambda_target", "dependencies": ["lambda_actual", "lambda_target"]}}},
        "visualization": {"heatmap": {"enabled": True, "x_axis": "rpm", "y_axis": "load",
                                      "rpm_bins": [500, 1500, 2500, 3500], "load_bins": [5, 35, 65, 95],
                                      "color_metric": "max", "cmap": "viridis"}},
        "output": {"summary_excel": True, "individual_csv": True, "error_log": True,
                   "metadata": {"project": "SYNTHETIC_DEMO", "vehicle": "SYNTHETIC_ONLY", "user": "SYNTHETIC_DEMO"}}})
    # The field layout matches an existing adapter; all numbers below are invented.
    dump(out / "obfcm_summary.json", {"synthetic": True,
        "Phase_Results": {f"Distance_Phase{i}_km": 10.0 for i in range(1, 5)},
        "Emissions": {"fuel_consumption": {**{f"phase{i}_FC_Bag_L_per_100km": 6.0 for i in range(1, 5)},
                                             "Total_FC_Bag_L_per_100km": 6.0}}})
    dump(out / "obfcm_analysis.json", {"synthetic": True, "initial_final_delta": {
        "engine_fuel_cumulative": {"initial": 0.0, "final": 2.352, "delta": 2.352, "channel": "synthetic_fuel_total"}}})
    dump(out / "expected.json", {"synthetic": True, "measurements": expected,
        "obfcm": {"total_distance_km": 40.0, "bag_cumulative_L": 2.4, "obfcm_cumulative_L": 2.352, "accuracy_percent": 2.0}})
    manifest = {"synthetic": True, "contains_real_measurements": False, "contains_real_calibration": False,
                "samples_per_file": 601, "duration_s": 60.0, "sample_rate_hz": 10,
                "measurement_files": 9, "channels_per_file": len(channels),
                "reproducibility": "Signal values and scenario definitions are deterministic; MF4 write-history timestamps may vary.",
                "files": {p.relative_to(out).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
                          for p in sorted(out.rglob("*")) if p.is_file()}}
    dump(out / "manifest.json", manifest)
    return manifest


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, default=Path(__file__).resolve().parent / "generated")
    args = parser.parse_args()
    generate(args.output_dir.resolve())
    print("Created 9 synthetic MF4 files, an A2L fixture, a wiki source, configs, expected results, and checksums.")
